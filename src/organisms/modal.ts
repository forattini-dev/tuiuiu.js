/**
 * Modal/Window Component - Pop-up dialogs for Tuiuiu
 *
 * Features:
 * - Centered modal dialogs
 * - Floating windows with position
 * - Confirmation dialogs
 * - Alert/info boxes
 * - Toast notifications
 * - Backdrop overlay
 *
 * @example
 * ```typescript
 * import { Modal, ConfirmDialog, Toast, openModal } from './modal.js';
 *
 * // Simple modal
 * When(showModal(),
 *   Modal({
 *     title: 'Settings',
 *     content: SettingsForm(),
 *     onClose: () => setShowModal(false)
 *   })
 * )
 *
 * // Confirmation dialog
 * ConfirmDialog({
 *   title: 'Delete File?',
 *   message: 'This action cannot be undone.',
 *   onConfirm: handleDelete,
 *   onCancel: closeDialog
 * })
 * ```
 */

